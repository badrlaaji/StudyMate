def result_rows(reports: dict[str, dict]) -> str:
    """Build the evaluation table rows from {label: report}."""
    rows = []
    for label, report in reports.items():
        for lang, name in (("en", "English"), ("fr", "French")):
            row = report[lang]
            rows.append(
                f"| {label} | {name} | {row['hit@4']:.3f} | {row['mrr@10']:.3f} |"
            )
    return "\n".join(rows)


def card_text(reports: dict[str, dict], pairs: int, repo_id: str) -> str:
    """Fill the model card template."""
    return CARD.format(
        base=BASE_MODEL,
        project=PROJECT_URL,
        repo_id=repo_id,
        pairs=pairs,
        epochs=EPOCHS,
        lr=LEARNING_RATE,
        rows=result_rows(reports),
        book=BOOK_URL,
    )


def load_report(model_label: str) -> dict:
    """Read the test report of one model."""
    path = RESULTS_DIR / f"retrieval_test_all-pages_{model_label}.json"
    return json.loads(path.read_text(encoding="utf-8"))


def main() -> None:
    """Write the card into the model folder and upload the folder."""
    repo_id = get_env("HF_REPO_ID", DEFAULT_REPO_ID)
    reports = {
        "e5-small (base)": load_report("multilingual-e5-small"),
        "this model": load_report("e5-small-studymate"),
    }
    pairs = json.loads(INFO_PATH.read_text(encoding="utf-8"))["pairs_kept"]
    (MODEL_DIR / "README.md").write_text(
        card_text(reports, pairs, repo_id), encoding="utf-8"
    )
    api = HfApi(token=get_env("HF_TOKEN"))
    api.create_repo(repo_id, repo_type="model", exist_ok=True)
    api.upload_folder(folder_path=str(MODEL_DIR), repo_id=repo_id, repo_type="model")
    print(f"published https://huggingface.co/{repo_id}")


if __name__ == "__main__":
    main()
